import { test, expect } from '@playwright/test'

test('specialist publishes a profile, creates a shift and appears in catalog', async ({ page }) => {
  await page.goto('/register')
  await page.getByRole('radio', { name: /^Специалист/ }).check()
  await page.getByRole('button', { name: 'Продолжить' }).click()
  const name = `Специалист ${Date.now()}`
  await page.getByLabel('Имя', { exact: true }).fill(name)
  await page.getByLabel('Email', { exact: true }).fill(`professional-${Date.now()}@example.com`)
  await page.getByLabel('Пароль', { exact: true }).fill('professional-test-password')
  await page.getByLabel('Повторите пароль').fill('professional-test-password')
  await page.getByLabel('Категория', { exact: true }).selectOption('law')
  await page.getByRole('button', { name: 'Зарегистрироваться' }).click()
  await expect(page).toHaveURL('/dashboard')
  await page.getByRole('link', { name: 'Публичный профиль', exact: true }).click()
  await page.getByRole('button', { name: 'Опубликовать', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Заполните')
  await page.getByLabel('Специализация', { exact: true }).fill('Юрист по договорам')
  await page.getByLabel('Краткое описание').fill('Помощь с договорами')
  await page
    .getByLabel('О себе', { exact: true })
    .fill('Консультирую по договорам и трудовым отношениям.')
  await page.getByLabel('Город', { exact: true }).fill('Омск')
  await page.getByLabel('Онлайн', { exact: true }).check()
  await page.getByRole('button', { name: 'Добавить услугу' }).click()
  await page.getByLabel('Название услуги 1').fill('Консультация')
  await page.getByLabel('Описание услуги 1').fill('Разбор договора')
  await page.getByRole('button', { name: 'Сохранить профиль' }).click()
  await expect(page.getByRole('status')).toHaveText('Изменения сохранены')
  await page.getByRole('button', { name: 'Опубликовать', exact: true }).click()
  await expect(page.getByText('Статус: Опубликован', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Создать смены', exact: true }).click()
  for (const day of ['Пн', 'Вт', 'Ср', 'Чт', 'Пт', 'Сб', 'Вс'])
    await page.getByLabel(day, { exact: true }).check()
  await page.getByLabel('Начало смены').fill('09:00')
  await page.getByLabel('Конец смены').fill('11:00')
  await page.getByRole('button', { name: 'Предпросмотр' }).click()
  await expect(page.getByRole('status')).toHaveText('Будет создано интервалов: 4')
  await page.getByRole('button', { name: 'Создать интервалы' }).click()
  await expect(page.getByRole('status')).toHaveText('Создано интервалов: 4')
  await page.goto('/')
  await page.getByLabel('Поиск', { exact: true }).fill(name)
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Посмотреть профиль' }).click()
  await expect(page.getByRole('heading', { name: 'Консультация', exact: true })).toBeVisible()
  await page.goto('/dashboard/professional')
  await page.getByRole('button', { name: 'Снять с публикации' }).click()
  await expect(page.getByText('Статус: Черновик', { exact: true })).toBeVisible()
  await page.goto(`/?q=${encodeURIComponent(name)}`)
  await expect(page.getByRole('heading', { name: 'Специалистов пока нет' })).toBeVisible()
  for (const width of [390, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
})
